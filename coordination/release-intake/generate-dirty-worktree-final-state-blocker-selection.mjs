#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const args = process.argv.slice(2);
if (args.includes("--help") || args.includes("-h")) {
  console.log(usage());
  process.exit(0);
}
if (args.length > 0) {
  console.error(`Unknown argument(s): ${args.join(", ")}`);
  console.error(usage());
  process.exit(1);
}

const root = git(["rev-parse", "--show-toplevel"]);
const date = hktDateStamp();

const paths = {
  dirtyMap: "coordination/release-intake/latest-A25-dirty-tree-map.json",
  template: "coordination/release-intake/latest-A25-dirty-worktree-final-state-selection-template.json",
  ownerDecisionPacket: "coordination/release-intake/latest-A25-dirty-worktree-final-state-owner-decision-packet.json",
  actionRunbook: "coordination/release-intake/latest-A25-dirty-worktree-final-state-action-runbook.json",
  selection: "coordination/release-intake/latest-A25-dirty-worktree-final-state-selection.json",
  datedSelection: `coordination/release-intake/${date}-A25-dirty-worktree-final-state-blocker-selection.json`,
  datedMarkdown: `coordination/release-intake/${date}-A25-dirty-worktree-final-state-blocker-selection.md`,
  latestMarkdown: "coordination/release-intake/latest-A25-dirty-worktree-final-state-blocker-selection.md"
};

const blockerApprover = "A25 git hygiene and release intake";
const blockerDecision = [
  "A25 blocker classification only.",
  "The row remains blocked because package/lifecycle cleanup still needs owning-agent or owner review and explicit authorization.",
  "This blocker selection authorizes no staging, commit, discard, tag, push, reset, restore, clean, deploy, branch deletion, worktree removal, or prune operation."
].join(" ");

function git(args, cwd = process.cwd()) {
  return execFileSync("git", args, {
    cwd,
    encoding: "utf8",
    maxBuffer: 128 * 1024 * 1024,
    stdio: ["ignore", "pipe", "pipe"]
  }).trim();
}

function hktDateStamp() {
  return new Intl.DateTimeFormat("en-CA", {
    timeZone: "Asia/Hong_Kong",
    year: "numeric",
    month: "2-digit",
    day: "2-digit"
  }).format(new Date());
}

function exists(relativePath) {
  return fs.existsSync(path.join(root, relativePath));
}

function readJson(relativePath) {
  return JSON.parse(fs.readFileSync(path.join(root, relativePath), "utf8"));
}

function write(relativePath, content) {
  fs.writeFileSync(path.join(root, relativePath), content);
}

function usage() {
  return `Usage: node coordination/release-intake/generate-dirty-worktree-final-state-blocker-selection.mjs

Generates a blocker-only final-state selection from the current A25 final-state template.
This records blockers only and authorizes no cleanup operation.

Options:
  -h, --help  Print this help without reading or writing repository artifacts.`;
}

function blockerSelectionRow(decision, approvedAt) {
  if (!decision.allowedFinalStates.includes("blocker")) {
    throw new Error(`${decision.ledgerId}: blocker is not an allowed final state`);
  }

  return {
    ledgerId: decision.ledgerId,
    sourceKind: decision.sourceKind,
    approvalId: decision.approvalId,
    owner: decision.owner,
    branch: decision.branch,
    path: decision.path,
    packageKind: decision.packageKind,
    priority: decision.priority,
    entries: decision.entries,
    currentBlocker: decision.currentBlocker,
    allowedFinalStates: decision.allowedFinalStates,
    selectedFinalState: "blocker",
    approvedBy: blockerApprover,
    approvedAt,
    ownerDecision: blockerDecision,
    evidenceReviewed: [
      ...(decision.evidenceReviewed ?? []),
      paths.ownerDecisionPacket,
      paths.actionRunbook
    ],
    notes: "Blocker-only selection generated by A25 to close missing final-state records without authorizing cleanup."
  };
}

function summarize(rows) {
  return Object.values(rows).reduce((summary, row) => {
    summary.total += 1;
    summary.bySourceKind[row.sourceKind] = (summary.bySourceKind[row.sourceKind] ?? 0) + 1;
    summary.byPackageKind[row.packageKind] = (summary.byPackageKind[row.packageKind] ?? 0) + 1;
    if (row.priority !== null && row.priority !== undefined) {
      summary.byPriority[`P${row.priority}`] = (summary.byPriority[`P${row.priority}`] ?? 0) + 1;
    }
    return summary;
  }, { total: 0, bySourceKind: {}, byPackageKind: {}, byPriority: {} });
}

function ownerOrBranch(row) {
  if (row.sourceKind === "owner-package") return row.owner;
  return row.branch || row.path || row.owner;
}

function markdown(payload) {
  const rows = Object.values(payload.decisions).map((row) => {
    return `| \`${row.ledgerId}\` | ${row.sourceKind} | ${ownerOrBranch(row)} | ${row.currentBlocker} | ${row.selectedFinalState} | ${row.approvedBy} |`;
  }).join("\n");

  return `# A25 Dirty-Worktree Final-State Blocker Selection

Generated: ${payload.generatedAt}

Dirty map signature: \`${payload.dirtyMapStatusSignature}\`

Expanded dirty entries: ${payload.expandedStatusEntries}

Selection target written: \`${paths.selection}\`

Rows: ${payload.summary.total}

This selection records blocker final states only. It is not approval for staging, committing, discarding, tagging, pushing, pruning, deploying, branch deletion, reset, clean, worktree removal, or any other physical cleanup. Physical cleanup remains blocked until owning agents or the owner provide explicit action approval.

| Ledger ID | Source kind | Owner or branch | Current blocker | Final state | Recorded by |
| --- | --- | --- | --- | --- | --- |
${rows}
`;
}

function main() {
  for (const requiredPath of [paths.dirtyMap, paths.template, paths.ownerDecisionPacket, paths.actionRunbook]) {
    if (!exists(requiredPath)) throw new Error(`Missing required file: ${requiredPath}`);
  }

  const dirtyMap = readJson(paths.dirtyMap);
  const template = readJson(paths.template);
  const packet = readJson(paths.ownerDecisionPacket);
  const runbook = readJson(paths.actionRunbook);

  for (const [label, artifact] of [["template", template], ["owner decision packet", packet], ["action runbook", runbook]]) {
    if (artifact.dirtyMapStatusSignature !== dirtyMap.statusSignature) {
      throw new Error(`${label} is stale relative to latest dirty map.`);
    }
  }

  const approvedAt = new Date().toISOString();
  const decisions = Object.fromEntries(
    Object.values(template.decisions ?? {}).map((decision) => {
      const row = blockerSelectionRow(decision, approvedAt);
      return [row.ledgerId, row];
    })
  );

  const payload = {
    generatedAt: approvedAt,
    dirtyMapStatusSignature: dirtyMap.statusSignature,
    expandedStatusEntries: dirtyMap.statusCounts.expandedStatusEntries,
    ownerPackageApprovalRequestsGeneratedAt: template.ownerPackageApprovalRequestsGeneratedAt,
    physicalLifecycleApprovalRequestsGeneratedAt: template.physicalLifecycleApprovalRequestsGeneratedAt,
    selectionMode: "blocker-only",
    cleanupAuthorized: false,
    note: blockerDecision,
    summary: summarize(decisions),
    decisions
  };

  const json = `${JSON.stringify(payload, null, 2)}\n`;
  write(paths.selection, json);
  write(paths.datedSelection, json);
  const md = markdown(payload);
  write(paths.latestMarkdown, md);
  write(paths.datedMarkdown, md);

  console.log(JSON.stringify({
    selection: paths.selection,
    datedSelection: paths.datedSelection,
    latestMarkdown: paths.latestMarkdown,
    datedMarkdown: paths.datedMarkdown,
    decisions: payload.summary.total,
    cleanupAuthorized: payload.cleanupAuthorized
  }, null, 2));
}

main();

const MINUS = '−'; /* U+2212 */

const fmtInt = (n) => (n < 0 ? MINUS + String(-n) : String(n));
const gcdOf = (x, y) => {
  x = Math.abs(x);
  y = Math.abs(y);
  while (y) {
    const t = x % y;
    x = y;
    y = t;
  }
  return x || 1;
};

/* a flat region on the lathe */
const regionText = (rg) =>
  rg.kind === 'rect'
    ? `the ${rg.w}-by-${rg.h} rectangle`
    : rg.kind === 'tri'
      ? `the right triangle, base ${rg.w}, height ${rg.h}`
      : `the half-disc of radius ${rg.r}`;

/* one law each: what the spin births */
const solidOf = (rg) => (rg.kind === 'rect' ? 'cylinder' : rg.kind === 'tri' ? 'cone' : 'sphere');

/* the volume's coefficient of π, as a reduced exact fraction */
const coefOf = (rg) => {
  let n;
  let d;
  if (rg.kind === 'rect') {
    n = rg.w * rg.w * rg.h;
    d = 1;
  } else if (rg.kind === 'tri') {
    n = rg.w * rg.w * rg.h;
    d = 3;
  } else {
    n = 4 * rg.r * rg.r * rg.r;
    d = 3;
  }
  const g = gcdOf(n, d);
  return [n / g, d / g];
};
const coefText = ([n, d]) => (d === 1 ? String(n) : `${n}/${d}`);
const volumeText = (rg) => `${coefText(coefOf(rg))}π`;

/* the lesson's posted regions */
const SCENES = {
  cyl: { kind: 'rect', w: 3, h: 4 },
  cone: { kind: 'tri', w: 3, h: 6 },
  sph: { kind: 'half', r: 3 },
  dial: { kind: 'rect', w: 3, h: 4 },
};

/* ---------------------------------------------------------------------------
   CALIBRATION — posted regions; truths derived from the lathe's laws.
   ------------------------------------------------------------------------- */
const CASES = [
  { kind: 'rect', w: 3, h: 4 },
  { kind: 'half', r: 3 },
  { kind: 'tri', w: 3, h: 6 },
  { kind: 'rect', w: 2, h: 5 },
  { kind: 'tri', w: 2, h: 6 },
  { kind: 'tri', w: 3, h: 3 },
];
const SOLID_CHIPS = ['cylinder', 'cone', 'sphere'];
const COEF_CHIPS = ['8', '9', '18', '20', '36'];

const labelOf = (i) => regionText(CASES[i]);
const solidTruth = (i) => solidOf(CASES[i]);
const coefTruth = (i) => coefText(coefOf(CASES[i]));

const makeCase = (prev) => {
  let k = Math.floor(Math.random() * CASES.length);
  while (CASES.length > 1 && k === prev) k = Math.floor(Math.random() * CASES.length);
  return k;
};

const calibChecks = (i, sPick, cPick) => {
  if (i == null) return [false, false];
  const c1 = sPick === solidTruth(i);
  const c2 = c1 && cPick === coefTruth(i);
  return [c1, c2];
};
const closeness = (i, sPick, cPick) => {
  const [c1, c2] = calibChecks(i, sPick, cPick);
  return (c1 ? 50 : 0) + (c2 ? 50 : 0);
};
const isCalibrated = (i, sPick, cPick) => calibChecks(i, sPick, cPick).every(Boolean);


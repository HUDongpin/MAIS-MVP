/* ============================================================================
   RevolutionLab — an interactive "bench" for SOLIDS OF REVOLUTION: the lathe.
   Spin a flat region about an axis and a solid appears — the rectangle turns
   into the cylinder, the right triangle into the cone, the half-disc into
   the sphere.  The three solid benches each measure their own solid; none of
   them shows WHERE the solids come from.  This bench is the common origin
   story, and every volume it posts is an exact integer (or exact fraction)
   times π.  (GRADES 9–12 · CCSS G-GMD.B.4 — identify three-dimensional
   objects generated by rotations of two-dimensional objects.)

   THE SIGNATURE CENTERPIECE — "THE LATHE AND THE VOLUME MANIFEST."  A gold
   axis runs vertically; the blue flat region hangs on its right; its faint
   mirror ghost on the left shows the sweep; and the carmine solid outline
   wraps both.  Beside the picture, the manifest prints the exact bill:
   spin the 3-by-4 rectangle and V = π·3²·4 = 36π; spin the 3-by-6 triangle
   and V = ⅓·π·3²·6 = 18π; spin the half-disc of radius 3 and V = 36π —
   and Archimedes' tombstone ratio, sphere to snug cylinder, lands on
   exactly 2/3.

   THE MODEL — exact integer/rational arithmetic throughout:
     · regions are {kind, dims}; solidOf reads the kind (rectangle →
       cylinder, right triangle → cone, half-disc → sphere) — one law each.
     · coefOf returns the volume's coefficient of π as a reduced exact
       fraction: [w²h, 1], [w²h, 3], [4r³, 3].  π itself is never
       evaluated; it rides as a symbol, and the audit proves every posted
       coefficient is an integer (dimensions are engineered so /3 divides).
     · the audit re-proves the cone = ⅓ of its bounding cylinder and the
       sphere = ⅔ of its snug cylinder as exact fraction identities, for
       every legal dimension in range — not just the posted ones.

   WHAT THIS LAB REFUSES TO DO (distinctness):
     · No formula derivations — the cylinder, cone, and sphere benches own
       measuring their own solids; each is cited as the destination bench,
       and the formulas arrive here as inherited freight.
     · No plane cuts, no flat shapes read off a solid — the cube-cutting
       bench owns that direction of G-GMD.B.4; this bench only ever goes
       flat-to-solid, never solid-to-flat.
     · No spinning animation — the sweep is drawn as a still ghost;
       requestAnimationFrame is banned by the audit.  Motion is implied,
       never performed.
     · No degree-slot machinery, no deposits — the polynomial bench owns
       its bookkeeping; this manifest tallies only coefficients of π.
   COLORS: one accent. CARMINE = the born solid (the object). GOLD = the
   axis and the manifest (the tool). BLUE = the quiet flat region. GREEN
   only on correct answers and the CALIBRATED stamp.

   THE CALIBRATION — a flat region is posted on the lathe.  Rule the solid
   it births first, then rule the volume's coefficient of π, exactly.
   Truths are derived from solidOf/coefOf at answer time; the meter is
   quantized to {0, 50, 100}; the coefficient earns nothing until the
   solid stands.  The stamp provably cannot fire falsely.
   ========================================================================== */

